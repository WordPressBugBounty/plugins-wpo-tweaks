	/* ============================
	 * Export
	 * ============================ */

	/**
	 * AJAX: Export settings as JSON.
	 */
	public function ajax_export() {
		check_ajax_referer( 'core_diet_tools_nonce', 'security' );

		if ( ! current_user_can( 'manage_options' ) ) {
			wp_send_json_error( __( 'Unauthorized.', 'wpo-tweaks' ), 403 );
		}

		$settings = get_option( Core_Diet_Settings::OPTION_NAME, Core_Diet_Settings::get_defaults() );

		$export = array(
			'plugin'   => 'dietpress',
			'version'  => CORE_DIET_VERSION,
			'exported' => current_time( 'c' ),
			'settings' => $settings,
		);

		wp_send_json_success( $export );
	}

	/* ============================
	 * Import
	 * ============================ */

	/**
	 * AJAX: Import settings from JSON.
	 */
	public function ajax_import() {
		check_ajax_referer( 'core_diet_tools_nonce', 'security' );

		if ( ! current_user_can( 'manage_options' ) ) {
			wp_send_json_error( __( 'Unauthorized.', 'wpo-tweaks' ), 403 );
		}

		if ( empty( $_FILES['file'] ) || ! isset( $_FILES['file']['name'] ) ) {
			wp_send_json_error( __( 'No file uploaded.', 'wpo-tweaks' ) );
		}

		// Validate file extension (.json not in WP default allowed types).
		$filename  = sanitize_file_name( wp_unslash( $_FILES['file']['name'] ) );
		$extension = strtolower( pathinfo( $filename, PATHINFO_EXTENSION ) );
		if ( 'json' !== $extension ) {
			wp_send_json_error( __( 'Invalid file type. Please upload a JSON file.', 'wpo-tweaks' ) );
		}

		// Read and parse file content. The tmp path is generated by PHP, and
		// is_uploaded_file() rejects anything that is not this request's upload.
		$tmp_path = isset( $_FILES['file']['tmp_name'] ) ? sanitize_text_field( wp_unslash( $_FILES['file']['tmp_name'] ) ) : '';
		if ( empty( $tmp_path ) || ! is_uploaded_file( $tmp_path ) ) {
			wp_send_json_error( __( 'Upload failed.', 'wpo-tweaks' ) );
		}

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- reading the PHP upload tmp file; WP_Filesystem transports (FTP, SSH) cannot access it.
		$content = file_get_contents( $tmp_path );
		if ( false === $content ) {
			wp_send_json_error( __( 'Could not read the uploaded file.', 'wpo-tweaks' ) );
		}

		$data = json_decode( $content, true );
		if ( json_last_error() !== JSON_ERROR_NONE || ! is_array( $data ) ) {
			wp_send_json_error( __( 'Invalid JSON format.', 'wpo-tweaks' ) );
		}

		// Validate it's a DietPress export. The legacy 'core-diet' id (used by
		// exports made before 3.1.0 and by the retired standalone plugin) is
		// still accepted for backward compatibility.
		$valid_ids = array( 'dietpress', 'core-diet' );
		if ( ! isset( $data['plugin'] ) || ! in_array( $data['plugin'], $valid_ids, true ) || ! isset( $data['settings'] ) ) {
			wp_send_json_error( __( 'This file is not a valid DietPress export.', 'wpo-tweaks' ) );
		}

		// Sanitize through the same callback used by Settings API.
		$sanitized = Core_Diet_Settings::sanitize( $data['settings'] );

		update_option( Core_Diet_Settings::OPTION_NAME, $sanitized );

		wp_send_json_success( array(
			'message' => __( 'Settings imported successfully.', 'wpo-tweaks' ),
		) );
	}

	/* ============================
	 * Profiles
	 * ============================ */

	/**
	 * AJAX: Apply a predefined profile.
	 */
	public function ajax_apply_profile() {
		check_ajax_referer( 'core_diet_tools_nonce', 'security' );

		if ( ! current_user_can( 'manage_options' ) ) {
			wp_send_json_error( __( 'Unauthorized.', 'wpo-tweaks' ), 403 );
		}

		$profile_id = isset( $_POST['profile'] ) ? sanitize_key( wp_unslash( $_POST['profile'] ) ) : '';
		$profiles   = self::get_profiles();

		// Reset to defaults: use default values directly.
		if ( 'reset' === $profile_id ) {
			$sanitized = Core_Diet_Settings::sanitize( Core_Diet_Settings::get_defaults() );
			update_option( Core_Diet_Settings::OPTION_NAME, $sanitized );

			wp_send_json_success( array(
				'message' => __( 'All settings restored to defaults.', 'wpo-tweaks' ),
			) );
		}

		if ( ! isset( $profiles[ $profile_id ] ) ) {
			wp_send_json_error( __( 'Invalid profile.', 'wpo-tweaks' ) );
		}

		$profile_settings = $profiles[ $profile_id ]['settings'];

		// Merge profile over defaults to ensure all keys exist.
		$new_settings = array_merge( Core_Diet_Settings::get_defaults(), $profile_settings );

		// Sanitize through the same callback.
		$sanitized = Core_Diet_Settings::sanitize( $new_settings );

		update_option( Core_Diet_Settings::OPTION_NAME, $sanitized );

		wp_send_json_success( array(
			'message' => sprintf(
				/* translators: %s: profile name */
				__( 'Profile "%s" applied successfully.', 'wpo-tweaks' ),
				$profiles[ $profile_id ]['label']
			),
		) );
	}

