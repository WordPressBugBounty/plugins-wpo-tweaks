	 * Savings calculation
	 * ============================ */

	/**
	 * Calculate estimated savings based on active settings.
	 *
	 * Static estimates per option. Values are approximate and based on
	 * typical WordPress installations.
	 *
	 * @return array With keys: requests, kb, queries, active_count, total_count.
	 */
	public static function calculate_savings() {
		$settings = Core_Diet_Settings::get_instance();

		// Estimated savings per option: array( requests, kb, queries ).
		// Single source of truth, shared with the analyzer (get_savings_estimates).
		$estimates = self::get_savings_estimates();

		$totals = array(
			'requests'     => 0,
			'kb'           => 0.0,
			'queries'      => 0,
			'active_count' => 0,
			'total_count'  => count( $estimates ),
		);

		foreach ( $estimates as $key => $values ) {
			if ( $settings->is_enabled( $key ) ) {
				$totals['requests'] += $values[0];
				$totals['kb']       += $values[1];
				$totals['queries']  += $values[2];
				$totals['active_count']++;
			}
		}

		// Non-boolean savings.
		$heartbeat_mode = $settings->get( 'heartbeat_mode' );
		if ( 'disable' === $heartbeat_mode ) {
			$totals['requests'] += 1;
			$totals['kb']       += 4.0;
			$totals['active_count']++;
		} elseif ( 'reduce' === $heartbeat_mode || 'admin_only' === $heartbeat_mode ) {
			$totals['requests'] += 1;
			$totals['active_count']++;
		}
		$totals['total_count']++;

		$revisions_mode = $settings->get( 'revisions_mode' );
		if ( 'disable' === $revisions_mode ) {
			$totals['queries'] += 3;
			$totals['active_count']++;
		} elseif ( 'limit' === $revisions_mode ) {
			$totals['queries'] += 1;
			$totals['active_count']++;
		}
		$totals['total_count']++;

		$autosave = (int) $settings->get( 'autosave_interval' );
		if ( 60 !== $autosave ) {
			$totals['active_count']++;
			if ( 0 === $autosave ) {
				$totals['requests'] += 1;
				$totals['kb']       += 3.0;
			}
		}
		$totals['total_count']++;

		return $totals;
	}
