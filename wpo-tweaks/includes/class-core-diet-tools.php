	/**
	 * AJAX: Save multiple recommendation settings at once.
	 *
	 * Receives a JSON object of key => boolean pairs and updates
	 * only those keys in the current settings.
	 */
	public function ajax_save_recommendations() {
		check_ajax_referer( 'core_diet_tools_nonce', 'security' );

		if ( ! current_user_can( 'manage_options' ) ) {
			wp_send_json_error( __( 'Unauthorized.', 'wpo-tweaks' ), 403 );
		}

		$raw = isset( $_POST['settings'] ) ? sanitize_text_field( wp_unslash( $_POST['settings'] ) ) : '';
		$changes = json_decode( $raw, true );

		if ( ! is_array( $changes ) || empty( $changes ) ) {
			wp_send_json_error( __( 'No settings to save.', 'wpo-tweaks' ) );
		}

		$defaults = Core_Diet_Settings::get_defaults();
		$settings = get_option( Core_Diet_Settings::OPTION_NAME, $defaults );

		foreach ( $changes as $key => $value ) {
			$key = sanitize_key( $key );
			if ( ! array_key_exists( $key, $defaults ) ) {
				continue;
			}
			$settings[ $key ] = (bool) $value;
		}

		$sanitized = Core_Diet_Settings::sanitize( $settings );
		update_option( Core_Diet_Settings::OPTION_NAME, $sanitized );

		wp_send_json_success();
	}

	/**
	 * Restore default values for a single tab.
	 *
	 * Resets only the settings that belong to the specified tab,
	 * leaving all other tabs untouched.
	 */
	public function ajax_restore_tab() {
		check_ajax_referer( 'core_diet_tools_nonce', 'security' );

		if ( ! current_user_can( 'manage_options' ) ) {
			wp_send_json_error( __( 'Unauthorized.', 'wpo-tweaks' ), 403 );
		}

		$tab = isset( $_POST['tab'] ) ? sanitize_key( wp_unslash( $_POST['tab'] ) ) : '';

		$allowed_tabs = array( 'light', 'moderate', 'strict', 'widgets', 'emails' );
		if ( ! in_array( $tab, $allowed_tabs, true ) ) {
			wp_send_json_error( __( 'Invalid tab.', 'wpo-tweaks' ) );
		}

		$tab_keys = Core_Diet_Settings::get_tab_keys( $tab );
		if ( empty( $tab_keys ) ) {
			wp_send_json_error( __( 'No settings found for this tab.', 'wpo-tweaks' ) );
		}

		$defaults = Core_Diet_Settings::get_defaults();
		$current  = get_option( Core_Diet_Settings::OPTION_NAME, $defaults );

		// Only overwrite the keys that belong to this tab.
		foreach ( $tab_keys as $key ) {
			if ( array_key_exists( $key, $defaults ) ) {
				$current[ $key ] = $defaults[ $key ];
			}
		}

		$sanitized = Core_Diet_Settings::sanitize( $current );
		update_option( Core_Diet_Settings::OPTION_NAME, $sanitized );

		wp_send_json_success();
	}

	/**
	 * Analyze the site and return actionable recommendations.
	 *
	 * Only suggests options that are currently disabled (not yet activated).
	 *
	 * @return array
	 */
	public function get_recommendations() {
		$settings        = Core_Diet_Settings::get_instance();
		$recommendations = array();

		// --- Light tab: always safe ---

		$light_always_safe = array(
			'disable_emojis'         => __( 'Modern browsers render emojis natively. Disabling saves 1 HTTP request and ~16 KB.', 'wpo-tweaks' ),
			'disable_rsd_link'       => __( 'RSD link is only needed for XML-RPC clients. Safe to remove.', 'wpo-tweaks' ),
			'disable_wlw_manifest'   => __( 'Windows Live Writer has been discontinued. This serves no purpose.', 'wpo-tweaks' ),
			'disable_shortlink'      => __( 'The ?p=123 shortlink is rarely used and adds nothing.', 'wpo-tweaks' ),
			'disable_self_pingbacks' => __( 'Prevents your site from pinging itself. No downside.', 'wpo-tweaks' ),
			'disable_capital_p'      => __( 'The auto-correction filter is cosmetic and unnecessary.', 'wpo-tweaks' ),
			'disable_comment_pagination' => __( 'Comment pagination creates thin content and duplicate URLs. Safe to disable.', 'wpo-tweaks' ),
			'disable_wp_logo_admin_bar'  => __( 'The WordPress logo in the admin bar serves no functional purpose.', 'wpo-tweaks' ),
			'disable_image_editor'   => __( 'The media library image editor is rarely used. Skips its scripts in the admin.', 'wpo-tweaks' ),
		);

		foreach ( $light_always_safe as $key => $reason ) {
			if ( ! $settings->is_enabled( $key ) ) {
				$recommendations[] = array(
					'key'      => $key,
					'label'    => Core_Diet_Settings::get_field_label( $key ),
					'reason'   => $reason,
					'risk'     => 'safe',
					'tab'      => 'light',
				);
			}
		}

		// --- Moderate tab: conditional ---

		// jQuery Migrate: safe if no legacy plugins.
		if ( ! $settings->is_enabled( 'disable_jquery_migrate' ) ) {
			$recommendations[] = array(
				'key'    => 'disable_jquery_migrate',
				'label'  => Core_Diet_Settings::get_field_label( 'disable_jquery_migrate' ),
				'reason' => __( 'Only needed by plugins using deprecated jQuery methods. Most modern plugins work without it.', 'wpo-tweaks' ),
				'risk'   => 'moderate',
				'tab'    => 'moderate',
			);
		}

		// Block directory and remote patterns.
		if ( ! $settings->is_enabled( 'disable_block_directory' ) ) {
			$recommendations[] = array(
				'key'    => 'disable_block_directory',
				'label'  => Core_Diet_Settings::get_field_label( 'disable_block_directory' ),
				'reason' => __( 'Remote block directory adds external requests in the editor. Safe to disable.', 'wpo-tweaks' ),
				'risk'   => 'safe',
				'tab'    => 'moderate',
			);
		}

		if ( ! $settings->is_enabled( 'disable_remote_patterns' ) ) {
			$recommendations[] = array(
				'key'    => 'disable_remote_patterns',
				'label'  => Core_Diet_Settings::get_field_label( 'disable_remote_patterns' ),
				'reason' => __( 'Prevents WordPress from fetching remote block patterns, reducing editor load time.', 'wpo-tweaks' ),
				'risk'   => 'safe',
				'tab'    => 'moderate',
			);
		}

		// Dashicons on frontend.
		if ( ! $settings->is_enabled( 'disable_dashicons' ) ) {
			$recommendations[] = array(
				'key'    => 'disable_dashicons',
				'label'  => Core_Diet_Settings::get_field_label( 'disable_dashicons' ),
				'reason' => __( 'Dashicons CSS on the frontend is only needed for the admin bar. Safe for logged-out visitors.', 'wpo-tweaks' ),
				'risk'   => 'safe',
				'tab'    => 'moderate',
			);
		}

		// Avatars: suggest disabling if comments are disabled.
		if ( ! $settings->is_enabled( 'disable_avatars' ) ) {
			if ( $settings->is_enabled( 'disable_comments' ) ) {
				$recommendations[] = array(
					'key'    => 'disable_avatars',
					'label'  => Core_Diet_Settings::get_field_label( 'disable_avatars' ),
					'reason' => __( 'Comments are already disabled. Avatars serve no purpose and Gravatar requests waste bandwidth.', 'wpo-tweaks' ),
					'risk'   => 'safe',
					'tab'    => 'moderate',
				);
			}
		}

		// Comment threading.
		if ( ! $settings->is_enabled( 'disable_comment_threading' ) ) {
			$recommendations[] = array(
				'key'    => 'disable_comment_threading',
				'label'  => Core_Diet_Settings::get_field_label( 'disable_comment_threading' ),
				'reason' => __( 'Disabling nested replies removes the comment-reply.js script from the frontend.', 'wpo-tweaks' ),
				'risk'   => 'moderate',
				'tab'    => 'moderate',
			);
		}

		// --- Strict tab: conditional ---

		// Comments: check if site has any recent comments.
		if ( ! $settings->is_enabled( 'disable_comments' ) ) {
			$comment_counts = wp_count_comments();
			$total_comments = isset( $comment_counts->approved ) ? (int) $comment_counts->approved : 0;

			if ( 0 === $total_comments ) {
				$recommendations[] = array(
					'key'    => 'disable_comments',
					'label'  => Core_Diet_Settings::get_field_label( 'disable_comments' ),
					'reason' => __( 'Your site has no approved comments. Disabling comments removes unnecessary code and database queries.', 'wpo-tweaks' ),
					'risk'   => 'recommended',
					'tab'    => 'strict',
				);
			}
		}

		// Sitemap: check if SEO plugin provides one.
		if ( ! $settings->is_enabled( 'disable_sitemap' ) ) {
			$has_seo_sitemap = defined( 'WPSEO_VERSION' )
				|| class_exists( 'RankMath' )
				|| class_exists( 'AIOSEO\\Plugin\\AIOSEO' )
				|| defined( 'JEsuspended_PLUGIN_SLUG' );

			if ( $has_seo_sitemap ) {
				$recommendations[] = array(
					'key'    => 'disable_sitemap',
					'label'  => Core_Diet_Settings::get_field_label( 'disable_sitemap' ),
					'reason' => __( 'An SEO plugin with its own sitemap is active. The native WordPress sitemap is redundant.', 'wpo-tweaks' ),
					'risk'   => 'recommended',
					'tab'    => 'strict',
				);
			}
		}

		// RSS feed links in head: always safe.
		if ( ! $settings->is_enabled( 'disable_feed_links_head' ) ) {
			$recommendations[] = array(
				'key'    => 'disable_feed_links_head',
				'label'  => Core_Diet_Settings::get_field_label( 'disable_feed_links_head' ),
				'reason' => __( 'RSS discovery links in the HTML head are unnecessary if you do not actively use feeds.', 'wpo-tweaks' ),
				'risk'   => 'safe',
				'tab'    => 'strict',
			);
		}

		// Search feeds: safe if no feed readers expected.
		if ( ! $settings->is_enabled( 'disable_feed_search' ) ) {
			$recommendations[] = array(
				'key'    => 'disable_feed_search',
				'label'  => Core_Diet_Settings::get_field_label( 'disable_feed_search' ),
				'reason' => __( 'Search result feeds are rarely subscribed to and expose site queries.', 'wpo-tweaks' ),
				'risk'   => 'safe',
				'tab'    => 'strict',
			);
		}

		// Privacy tools: recommend for non-EU or single-author blogs.
		if ( ! $settings->is_enabled( 'disable_privacy_tools' ) ) {
			$recommendations[] = array(
				'key'    => 'disable_privacy_tools',
				'label'  => Core_Diet_Settings::get_field_label( 'disable_privacy_tools' ),
				'reason' => __( 'Built-in privacy tools can be removed if you handle GDPR compliance through a dedicated plugin.', 'wpo-tweaks' ),
				'risk'   => 'moderate',
				'tab'    => 'strict',
			);
		}

		// Selective loading: suggest each module when its target is present.
		if ( ! $settings->is_enabled( 'selective_woocommerce' ) && class_exists( 'WooCommerce' ) ) {
			$recommendations[] = array(
				'key'    => 'selective_woocommerce',
				'label'  => Core_Diet_Settings::get_field_label( 'selective_woocommerce' ),
				'reason' => __( 'WooCommerce loads its styles and scripts on every page. Selective loading removes them where there is no store content. Review the cart behavior if your theme has a custom header mini-cart.', 'wpo-tweaks' ),
				'risk'   => 'moderate',
				'tab'    => 'strict',
			);
		}

		if ( ! $settings->is_enabled( 'selective_cf7' ) && class_exists( 'WPCF7' ) ) {
			$recommendations[] = array(
				'key'    => 'selective_cf7',
				'label'  => Core_Diet_Settings::get_field_label( 'selective_cf7' ),
				'reason' => __( 'Contact Form 7 loads its assets on every page. Selective loading keeps them only where a form is detected.', 'wpo-tweaks' ),
				'risk'   => 'moderate',
				'tab'    => 'strict',
			);
		}

		if ( ! $settings->is_enabled( 'selective_blocks' )
			&& ( ! function_exists( 'wp_is_block_theme' ) || ! wp_is_block_theme() ) ) {
			$recommendations[] = array(
				'key'    => 'selective_blocks',
				'label'  => Core_Diet_Settings::get_field_label( 'selective_blocks' ),
				'reason' => __( 'Your classic theme loads the block library styles everywhere. Selective loading removes them on pages whose content uses no blocks.', 'wpo-tweaks' ),
				'risk'   => 'moderate',
				'tab'    => 'strict',
			);
		}

		// Heartbeat: suggest reducing if still default.
		if ( 'default' === $settings->get( 'heartbeat_mode' ) ) {
			$recommendations[] = array(
				'key'    => 'heartbeat_mode',
				'label'  => Core_Diet_Settings::get_field_label( 'heartbeat_mode' ),
				'reason' => __( 'Reducing the Heartbeat frequency saves AJAX requests without affecting auto-save reliability.', 'wpo-tweaks' ),
				'risk'   => 'moderate',
				'tab'    => 'strict',
				'value'  => 'reduce',
			);
		}

		// Revisions: suggest limiting if still default.
		if ( 'default' === $settings->get( 'revisions_mode' ) ) {
			$recommendations[] = array(
				'key'    => 'revisions_mode',
				'label'  => Core_Diet_Settings::get_field_label( 'revisions_mode' ),
				'reason' => __( 'Limiting revisions prevents database bloat. 10 revisions per post is usually more than enough.', 'wpo-tweaks' ),
				'risk'   => 'moderate',
				'tab'    => 'strict',
				'value'  => 'limit',
			);
		}

		return $recommendations;
	}

